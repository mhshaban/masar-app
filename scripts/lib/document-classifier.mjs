// جداول حصص الشعب ("جدول حصص الفصل الدراسي") مختلطة فعليًا بأرشيف
// الشهادات بمدارس حقيقية — ملف مؤسسي (مقرر/مدرس/غرفة/فترة لكل شعبة)، بلا
// أي رقم أكاديمي طالب حقيقي بداخله، لكنه مليء برموز مقررات متكررة قد
// تُلتقَط بالغلط كـ"مقررات طالب" لو صادف الملف رقمًا شبه رقم أكاديمي بمكان
// ما (رُصد فعليًا على أرشيف مدرسة حقيقي). يُستبعَد بالتعرّف على شكله
// مباشرة، لا بالاعتماد على فشل إيجاد رقم الطالب فقط.
export function looksLikeScheduleDocument(rawRows) {
  const text = rawRows.map((r) => r.join(" ")).join("\n");
  return text.includes("جدول حصص") || (text.includes("الشعبة") && text.includes("مقرر") && text.includes("مدرس") && text.includes("غرفة"));
}

