test("extractSectionSchedule reads the header metadata (section/level/track/specialization) from a real جدول حصص الفصل الدراسي PDF", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  assert.equal(result.section, "1تلم1");
  assert.equal(result.level, "الاول");
  assert.equal(result.track, "تأسيسي");
  assert.equal(result.specialization, "تأسيسي");
});

test("extractSectionSchedule produces one row per (day, period) cell that actually has a مقرر value — 8 periods × 5 days here", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  assert.equal(result.rows.length, 40);
});

test("extractSectionSchedule matches each field to the correct day column by x-coordinate, not array position", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  const row = result.rows.find((r) => r.day === 1 && r.period === 1);
  assert.deepEqual(row, {
    section: "1تلم1",
    day: 1,
    period: 1,
    subjectCode: "ريض813",
    teacher: "حسين يوسف",
    room: "A16E",
    session: 2, // مسائي
  });
});

test("extractSectionSchedule keeps a long combined-teacher name attached to its real day column despite its wide x-offset (real bug caught against this exact file)", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  const row = result.rows.find((r) => r.day === 1 && r.period === 3);
  assert.equal(row.subjectCode, "الك801");
  assert.equal(row.teacher, "خالد بدري+B JAIGANESH");
});

test("extractSectionSchedule leaves room null for a cell genuinely blank in the source PDF (بدن801, day 5 period 5) instead of shifting a neighboring day's value into it", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  const row = result.rows.find((r) => r.day === 5 && r.period === 5);
  assert.equal(row.subjectCode, "بدن801");
  assert.equal(row.teacher, "يعقوب يوسف");
  assert.equal(row.room, null);
  // اليوم المجاور (الأربعاء) يجب ألا يتأثر بالخانة الفارغة عند اليوم التالي له.
  const neighbor = result.rows.find((r) => r.day === 4 && r.period === 5);
  assert.equal(neighbor.room, "A112");
});

test("extractSectionSchedule never confuses the 'الحصة X' period-name label (which sometimes shares a text row with فترة) for a day's value", () => {
  const result = extractSectionSchedule(REAL_ITEMS);
  for (const row of result.rows) {
    assert.ok(!String(row.subjectCode).startsWith("الحصة"));
    assert.ok(!String(row.teacher).startsWith("الحصة"));
    assert.ok(!String(row.room).startsWith("الحصة"));
  }
});
